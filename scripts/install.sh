#!/bin/sh
# MusicNX installer (beta) for Raspberry Pi OS.
#
# Installs the server for the CURRENT user: a venv, a config with absolute
# paths, a systemd user service and a health check. Run from the repository
# root on the Pi:
#   ./scripts/install.sh [--data DIR] [--port N]
#
# System apt packages are NOT installed silently: when a required binary is
# missing the script prints the exact apt command and exits — run it and
# re-run the installer. The service must run under a normal user (not root)
# because audio zones rely on user-scoped PipeWire.

set -eu

APP_DIR="$(cd "$(dirname "$0")/.." && pwd)"
DATA_DIR="${HOME}/musicnx-data"
PORT=8080

while [ $# -gt 0 ]; do
  case "$1" in
    --data) DATA_DIR="$2"; shift 2 ;;
    --port) PORT="$2"; shift 2 ;;
    *) echo "Unknown option: $1" >&2; exit 2 ;;
  esac
done

say() { printf '\033[1;36m==>\033[0m %s\n' "$1"; }

if [ "$(id -u)" -eq 0 ]; then
  echo 'Do not run the installer as root: audio zones need a user-scoped' >&2
  echo 'PipeWire session. Re-run it as a normal user.' >&2
  exit 2
fi

say "MusicNX beta installer (app: $APP_DIR, data: $DATA_DIR, port: $PORT)"

# --- 1. System binaries ------------------------------------------------------
MISSING=""
for BIN in python3 mpv pactl systemctl curl; do
  command -v "$BIN" >/dev/null 2>&1 || MISSING="$MISSING $BIN"
done
if [ -n "$MISSING" ]; then
  echo 'Missing system packages:' >&2
  echo "  sudo apt update && sudo apt install -y$MISSING pipewire pipewire-pulse wireplumber avahi-daemon" >&2
  echo 'Run the command above, then re-run this installer.' >&2
  exit 2
fi
PY_OK=$(python3 -c 'import sys; print(1 if sys.version_info >= (3, 11) else 0)')
[ "$PY_OK" = "1" ] || { echo 'Python 3.11+ is required.' >&2; exit 2; }

# --- 2. Data directories -----------------------------------------------------
say 'Creating data directories (library, database, cache, downloads, backups)'
mkdir -p "$DATA_DIR/library" "$DATA_DIR/database" "$DATA_DIR/cache/covers" \
  "$DATA_DIR/cache/tmp" "$DATA_DIR/downloads" "$DATA_DIR/backups"

# --- 3. Virtualenv and pinned dependencies ----------------------------------
say 'Creating venv and installing pinned Python dependencies'
[ -d "$APP_DIR/venv" ] || python3 -m venv "$APP_DIR/venv"
"$APP_DIR/venv/bin/python" -m pip install --quiet --disable-pip-version-check \
  --upgrade pip
"$APP_DIR/venv/bin/python" -m pip install --quiet --disable-pip-version-check \
  -r "$APP_DIR/backend/requirements.txt"
"$APP_DIR/venv/bin/python" -m pip check

# --- 4. Minimal config with absolute paths -----------------------------------
say 'Writing config/config.yaml'
mkdir -p "$APP_DIR/config"
if [ -f "$APP_DIR/config/config.yaml" ]; then
  say 'config/config.yaml already exists — keeping it'
else
  cat > "$APP_DIR/config/config.yaml" <<EOF
# Generated by scripts/install.sh — edit freely; see config.example.yaml
# for every available option.
mode: real
server:
  host: 0.0.0.0
  port: $PORT
audio:
  backend: mpv
paths:
  database: $DATA_DIR/database/musicnx.db
  library: $DATA_DIR/library
  downloads: $DATA_DIR/downloads
  cache: $DATA_DIR/cache
  backups: $DATA_DIR/backups
logging:
  file: $DATA_DIR/musicnx.log
library:
  import_roots: [$DATA_DIR/library]
EOF
fi
chmod 600 "$APP_DIR/config/config.yaml"

# --- 5. systemd user service --------------------------------------------------
say 'Installing systemd user service'
mkdir -p "$HOME/.config/systemd/user"
cat > "$HOME/.config/systemd/user/musicnx.service" <<EOF
[Unit]
Description=MusicNX media server
After=network-online.target pipewire.service wireplumber.service
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory=$APP_DIR/backend
Environment=PYTHONUNBUFFERED=1
Environment=MUSICNX_CONFIG=$APP_DIR/config/config.yaml
Environment=MUSICNX_AUDIO__IPC_SOCKET=%t/musicnx/mpv.sock
ExecStartPre=/usr/bin/mkdir -p %t/musicnx
ExecStart=$APP_DIR/venv/bin/uvicorn app.main:app --host 0.0.0.0 --port $PORT
Restart=always
RestartSec=2
TimeoutStopSec=20
KillSignal=SIGTERM

[Install]
WantedBy=default.target
EOF

loginctl enable-linger "$(id -un)" 2>/dev/null || {
  echo 'Could not enable linger (needed to keep the service alive without' >&2
  echo 'a login session). Run: loginctl enable-linger "$USER"' >&2
}
systemctl --user daemon-reload
systemctl --user enable musicnx
systemctl --user restart musicnx

# --- 6. Health check -----------------------------------------------------------
say 'Waiting for the service (migrations run on first boot)'
OK=0
i=1
while [ "$i" -le 30 ]; do
  if curl -fsS "http://127.0.0.1:$PORT/api/v1/system/health" >/dev/null 2>&1; then
    OK=1
    break
  fi
  sleep 1
  i=$((i + 1))
done

IP=$(hostname -I 2>/dev/null | awk '{print $1}')
if [ "$OK" = "1" ]; then
  echo
  echo '  MusicNX is running.'
  echo "  UI:            http://${IP:-<pi-address>}:$PORT"
  echo "  Also try mDNS: http://$(hostname).local:$PORT"
  echo "  Put your music into: $DATA_DIR/library (Медиатека → Импортировать)."
  echo '  На странице «Система → Состояние» — QR-код: отсканируйте телефоном,'
  echo '  интерфейс откроется на нём.'
  echo '  Security: LAN-only. Do not expose port to the internet.'
else
  echo 'Health check failed. Inspect the logs:' >&2
  echo '  journalctl --user -u musicnx -n 100' >&2
  systemctl --user status musicnx --no-pager || true
  exit 1
fi
